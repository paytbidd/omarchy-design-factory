def occupied(rows: list[str]) -> list[tuple[int, int]]:
    cells = []
    for y, row in enumerate(rows):
        for x, cell in enumerate(row):
            if cell not in {".", " "}:
                cells.append((x, y))
    return cells


def centered(rows: list[str], size: int = 16) -> list[tuple[int, int]]:
    cells = occupied(rows)
    if not cells:
        return []
    xs = [x for x, _ in cells]
    ys = [y for _, y in cells]
    width = max(xs) - min(xs) + 1
    height = max(ys) - min(ys) + 1
    dx = (size - width) // 2 - min(xs)
    dy = (size - height) // 2 - min(ys)
    return [(x + dx, y + dy) for x, y in cells]


def svg_from_map(rows: list[str]) -> str:
    rects = [
        f'  <rect x="{x}" y="{y}" width="1" height="1"/>' for x, y in centered(rows)
    ]
    body = "\n".join(rects)
    return (
        '<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 16 16" '
        'shape-rendering="crispEdges" fill="currentColor" aria-hidden="true">\n'
        f"{body}\n"
        "</svg>\n"
    )


def main() -> None:
    ICONS.mkdir(parents=True, exist_ok=True)
    for name, rows in MAPS.items():
        path = ICONS / f"{name}.svg"
        path.write_text(svg_from_map(rows))
        print(path.relative_to(ROOT))


if __name__ == "__main__":
    main()
